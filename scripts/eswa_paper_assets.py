# --------------------------------------------------------------------------- convergence
def curves(folder, arm, inst):
    bench = BENCHES[folder]
    d = RAW / folder / "eswa_eigen" / bench / arm / f"inst{inst:02d}"
    C, cp = [], None
    for r in range(1, 31):
        z = np.load(d / f"run{r:02d}.npz")
        C.append(np.maximum(z["curve"], FLOOR))
        cp = z["checkpoints"]
    return cp, np.median(np.vstack(C), axis=0)


