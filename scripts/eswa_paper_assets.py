def cost(D):
    lines = []
    ratios = {}
    for f, d in D.items():
        x = d[d.method == "EIG50"].sort_values(["instance", "run_id"])
        y = d[d.method == "RND"].sort_values(["instance", "run_id"])
        ratios[f] = float(np.median(x.runtime_sec.to_numpy() / y.runtime_sec.to_numpy()))
        assert np.array_equal(x.FE.to_numpy(), y.FE.to_numpy())
    res("overhead-min", f"{100 * (min(ratios.values()) - 1):.1f}")
    res("overhead-max", f"{100 * (max(ratios.values()) - 1):.1f}")
    for a in ORDER:
        cells = [f"{d[d.method == a].runtime_sec.median():.1f}" for d in D.values()]
        lines.append(f"{LABEL[a]} & " + " & ".join(cells) + " \\\\")
    rr = " & ".join(f"{ratios[f]:.3f}" for f in D)
    write("tab_cost.tex", r"""\begin{table}[t]
\centering
\caption{Median wall-clock time per run in seconds (Python 3, NumPy, one core per run, 11 runs in parallel on a
12-core laptop; other jobs shared the machine, so times are indicative). Last row: median paired ratio of the run
times of EIG-MPHBS and MPHBS-R, which use identical evaluation counts.}
\label{tab:cost}
\small
\begin{tabular}{lcccc}
\toprule
Algorithm & C10 & C20 & B20 & FIR \\
\midrule
""" + "\n".join(lines) + "\n\\midrule\nEIG-MPHBS / MPHBS-R & " + rr + r""" \\
\bottomrule
\end{tabular}
\end{table}
""")


# --------------------------------------------------------------------------- convergence
def curves(folder, arm, inst):
    bench = BENCHES[folder]
    d = RAW / folder / "eswa_eigen" / bench / arm / f"inst{inst:02d}"
    C, cp = [], None
    for r in range(1, 31):
        z = np.load(d / f"run{r:02d}.npz")
        C.append(np.maximum(z["curve"], FLOOR))
        cp = z["checkpoints"]
    return cp, np.median(np.vstack(C), axis=0)


def fig_convergence():
    S1 = pd.read_csv(AN / "S1_all_instances.csv")
    pick = [("BBOB-D20", 10), ("BBOB-D20", 14), ("BBOB-D20", 19), ("BBOB-D20", 4)]
    for f in ("CEC2022-D20", "FIR"):
        g = S1[(S1.hyp == "H1") & (S1.bench == f) & (S1.A > 0.5)].sort_values("p_inst")
        pick.append((f, int(g.instance.iloc[0])))
    res("conv-C20", pick[4][1])
    res("conv-FIR", pick[5][1])
    fig, axes = plt.subplots(2, 3, figsize=(7.4, 4.9))
    for ax, (f, i) in zip(axes.flat, pick):
        for a, (col, ls, mk) in STYLE.items():
            cp, m = curves(f, a, i)
            ax.plot(cp, m, color=col, ls=ls, lw=1.6 if a == "EIG50" else 1.1, marker=mk, markersize=3.5,
                    markevery=25, label=LABEL[a], zorder=3 if a == "EIG50" else 2)
        ax.set_yscale("log")
        ax.set_title(f"{BLABEL[f].replace('$', '').replace('{=}', '=')}, {FNAME[f]}{i}", fontsize=8.5)
        ax.tick_params(labelsize=7)
        ax.xaxis.set_major_formatter(matplotlib.ticker.FuncFormatter(lambda v, _: f"{v / 1000:.0f}k" if v else "0"))
        ax.grid(color="#e6e5e0", lw=0.5)
        for s in ("top", "right"):
            ax.spines[s].set_visible(False)
    for ax in axes[1]:
        ax.set_xlabel("function evaluations", fontsize=8)
    for ax in axes[:, 0]:
        ax.set_ylabel("median error", fontsize=8)
    axes[1, 2].set_ylabel("median objective", fontsize=8)
    h, l = axes[0, 0].get_legend_handles_labels()
    fig.legend(h, l, loc="lower center", ncol=7, fontsize=7, frameon=False)
    fig.tight_layout(rect=(0, 0.05, 1, 1))
    fig.savefig(FIG / "fig_convergence.pdf")
    fig.savefig(FIG / "fig_convergence.png", dpi=200)
    plt.close(fig)


