    n = sum(len(d) for d in D.values()) + len(off)
    res("runs-total", f"{n:,}".replace(",", "{,}"))
    res("runs-arms", len(ORDER))
    H = confirmatory()
    fig_heldout(H)
    comparison(D)
    rotation()
    ea4eig()
