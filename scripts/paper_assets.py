def f3(x):
    return f"{x:.3f}"


def sci(x):
    """Compact scientific notation for medians in tables."""
    if x == 0:
        return "0"
    a = abs(x)
    if 1e-2 <= a < 1e4:
        return f"{x:.4g}"
    m, e = f"{x:.2e}".split("e")
    return f"${m}{{\\times}}10^{{{int(e)}}}$"


def ptex(p):
    if p != p:          # NaN
        return "--"
    if p < 1e-3:
        m, e = f"{p:.1e}".split("e")
        return f"${m}{{\\times}}10^{{{int(e)}}}$"
    return f"{p:.3f}" if p < 1 else "1"


def macros(s, h5, v3, integ):
    out = {}
    for level in ("primary", "secondary"):
        for key, c in s[level].items():
            hid, dom = key.split("/")
            k = f"{hid}-{dom}"
            out[f"{k}-wbar"] = f3(c["wbar"])
            out[f"{k}-ci"] = f"[{f3(c['ci_low'])}, {f3(c['ci_high'])}]"
            out[f"{k}-siga"] = str(c["n_sig_anchor"])
            out[f"{k}-sigc"] = str(c["n_sig_comparator"])
            out[f"{k}-n"] = str(c["n_instances"])
            out[f"{k}-verdict"] = c["verdict"]
    for arm, a in h5["arms"].items():
        out[f"H5-{ARM[arm]}-esc"] = str(a["escapes"])
        out[f"H5-{ARM[arm]}-n"] = str(a["n"])
        out[f"H5-{ARM[arm]}-ci"] = f"[{a['wilson_low']:.2f}, {a['wilson_high']:.2f}]"
    out["H5-mcnemar-p"] = f"{h5['mcnemar_first_two']['p']:.2f}"
    m, e = f"{h5['binomial_vs_authors']['p']:.1e}".split("e")
    out["H5-binom-p"] = f"{m}\\times10^{{{int(e)}}}"      # used inside math mode
    for dom, v in v3.items():
        out[f"V3-{dom}-differ"] = str(v["n_differ"])
        out[f"V3-{dom}-n"] = str(v["n_instances"])
    out["runs-total"] = f"{sum(v['n_runs'] for v in integ.values()):,}"
    for dom, v in integ.items():
        out[f"runs-{dom}"] = f"{v['n_runs']:,}"
    out["commit"] = s["git_commit"][:7]
    return out


def write_macros(m):
    lines = ["% generated by scripts/paper_assets.py from results/analysis/pathA -- do not edit",
             "\\providecommand\\res[1]{\\csname res@#1\\endcsname}"]
    for k, v in sorted(m.items()):
        lines.append(f"\\expandafter\\def\\csname res@{k}\\endcsname{{{v}}}")
    (GEN / "results.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


def verdict_cell(v):
    return {"anchor superior": "anchor", "comparator superior": "comparator",
            "practically equivalent": "equivalent"}.get(v, v)


SHORT = {"H6-Ni1-policy": "H6 policy, $N_i{=}1$", "H6-Ni3-policy": "H6 policy, $N_i{=}3$",
         "H6-Ni9-policy": "H6 policy, $N_i{=}9$", "H6-RND-Ni1-vs-default": "H6 $N_i{=}1$ vs default",
         "H6-RND-Ni-other-vs-default": "H6 other $N_i$ vs default", "H7-K1": "H7 $K{=}1$",
         "H7-GreedyAcc": "H7 greedy accept."}


def table_contrasts(s, level, path, caption, label):
    rows = []
    for key, c in s[level].items():
        hid, dom = key.split("/")
        rows.append(f"{SHORT.get(hid, hid)} & {DOM[dom]} & {ARM[c['anchor']]} & {ARM[c['comparator']]} & {c['runs']} & "
                    f"{c['n_sig_anchor']}/{c['n_sig_comparator']} & {f3(c['wbar'])} & "
                    f"[{f3(c['ci_low'])}, {f3(c['ci_high'])}] & {verdict_cell(c['verdict'])} \\\\")
    body = "\n".join(rows)
    tex = f"""% generated by scripts/paper_assets.py -- do not edit
\\begin{{table*}}[t]
\\centering
\\caption{{{caption}}}
\\label{{{label}}}
\\small
\\begin{{tabular}}{{llllrcccl}}
\\toprule
 & Domain & Anchor & Comparator & $n$ & Sig.\\ (A/C) & $\\bar W$ & 95\\% CI & Verdict \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
\\end{{table*}}
"""
    path.write_text(tex, encoding="utf-8")


