def figure(s):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.lines import Line2D
    plt.rcParams.update({"font.family": "sans-serif", "font.size": 7, "axes.edgecolor": INK2,
                         "axes.labelcolor": INK, "xtick.color": INK2, "ytick.color": INK2,
                         "pdf.fonttype": 42})
    hs = ["H1", "H2a", "H2b", "H3", "H4"]
    doms = ["CEC2022", "FIR"]
    fig, axes = plt.subplots(len(hs), 2, figsize=(7.0, 8.6), sharex=True,
                             gridspec_kw={"width_ratios": [12, 8]})
    for i, h in enumerate(hs):
        for j, dom in enumerate(doms):
            ax = axes[i, j]
            key = f"{h}/{dom}"
            ax.set_xlim(-0.03, 1.03)
            for side in ("top", "right"):
                ax.spines[side].set_visible(False)
            if key not in s["primary"]:
                ax.set_axis_off()
                ax.text(0.5, 0.5, "not applicable (memory already\nsynchronised on FIR)", ha="center",
                        va="center", color=INK2, fontsize=6.5, transform=ax.transAxes)
                continue
            c = s["primary"][key]
            T = pd.read_csv(AN / "tables" / f"primary_{h}_{dom}.csv")
            y = list(range(len(T)))[::-1]
            ax.axvline(0.5, color=GREY, lw=0.8, ls=(0, (2, 2)), zorder=0)
            ax.axvspan(c["ci_low"], c["ci_high"], color=BLUE if c["wbar"] > 0.5 else ORANGE,
                       alpha=0.12, lw=0, zorder=0)
            ax.axvline(c["wbar"], color=INK2, lw=1.0, zorder=1)
            for yy, r in zip(y, T.itertuples()):
                if r.significant_favours == "anchor":
                    ax.plot(r.w, yy, "o", ms=4.5, color=BLUE, mec="white", mew=0.6, zorder=3)
                elif r.significant_favours == "comparator":
                    ax.plot(r.w, yy, "v", ms=5, color=ORANGE, mec="white", mew=0.6, zorder=3)
                else:
                    ax.plot(r.w, yy, "o", ms=4, mfc="white", mec=GREY, mew=0.9, zorder=2)
            pref = "F" if dom == "CEC2022" else "C"
            ax.set_yticks(y)
            ax.set_yticklabels([f"{pref}{k}" for k in T.instance], fontsize=5.2)
            ax.set_ylim(-0.8, len(T) - 0.2)
            ax.tick_params(axis="y", length=0)
            ax.set_title(f"{h} ({QUESTION[h]}): {ARM[c['anchor']]} vs {ARM[c['comparator']]}",
                         fontsize=6.8, loc="left", color=INK)
            if i == 0:
                ax.text(1.0, 1.22, dom, transform=ax.transAxes, ha="right", fontsize=7.5,
                        fontweight="bold", color=INK)
    for ax in axes[-1]:
        ax.set_xlabel("paired win probability of the first arm ($\\hat w$)")
    handles = [Line2D([], [], marker="o", ls="", color=BLUE, mec="white", label="significant, favours first arm"),
               Line2D([], [], marker="v", ls="", color=ORANGE, mec="white", label="significant, favours second arm"),
               Line2D([], [], marker="o", ls="", mfc="white", mec=GREY, label="not significant (Holm)"),
               Line2D([], [], color=INK2, lw=1.0, label="$\\bar W$ (shaded: 95% CI)")]
    fig.legend(handles=handles, loc="lower center", ncol=4, frameon=False, fontsize=6.5,
               bbox_to_anchor=(0.5, -0.005))
    fig.tight_layout(rect=(0, 0.035, 1, 1), h_pad=0.9, w_pad=1.5)
    FIG.mkdir(parents=True, exist_ok=True)
    fig.savefig(FIG / "fig_instances.pdf")
    fig.savefig(FIG / "fig_instances.png", dpi=200)


def instance_macros():
    """Per-instance medians and win probabilities of every contrast table, e.g. \\res{H2b-CEC2022-i5-amed}."""
    out = {}
    for f in sorted((AN / "tables").glob("*.csv")):
        _, hid, dom = f.stem.split("_", 2)
        for r in pd.read_csv(f).itertuples():
            k = f"{hid}-{dom}-i{r.instance}"
            out[f"{k}-amed"] = sci(r.anchor_median).strip("$")
            out[f"{k}-cmed"] = sci(r.comparator_median).strip("$")
            out[f"{k}-w"] = f"{r.w:.2f}"
    return out


def authors_reanalysis():
    """The authors' own SARSA-vs-RANDOM-mirror evidence, re-analysed with this repo's tests:
    paired Wilcoxon (stats.wilcoxon_p) per instance on their 30 common-seed runs, Holm within domain."""
    from lakaie.analysis.stats import TIE_TOL, holm, wilcoxon_p
    ref = ROOT / "third_party" / "mphbs_reference" / "results"
    spec = {"CEC2022": ("CEC2022_ablation_BC1_common_seeds", "FunctionID", "Error", "BS-C1", "BR-C1", "MPHB"),
            "FIR": ("FIR_ablation_AC1_common_seeds", "CaseID", "BestFit", "AS-C1", "AR-C1", "MPHB")}
    out = {}
    for dom, (d, ic, vc, sarsa, rnd, mphb) in spec.items():
        T = pd.read_csv(ref / d / "task_results.csv")
        fe_col = "EstFEs" if "EstFEs" in T.columns else "FEs"
        for alias, name in ((sarsa, "SARSA"), (rnd, "RANDOM"), (mphb, "MPHB")):
            out[f"auth-{dom}-{name}-fe"] = f"{int(T[T.Alias == alias][fe_col].iloc[0]):,}"
        for comp, name in ((rnd, "RANDOM"), (mphb, "MPHB")):
            ps, fav, wins, losses = [], [], 0, 0
            for inst in sorted(T[ic].unique()):
                a = T[(T.Alias == sarsa) & (T[ic] == inst)].sort_values("RunIdx")[vc].to_numpy(float)
                b = T[(T.Alias == comp) & (T[ic] == inst)].sort_values("RunIdx")[vc].to_numpy(float)
                diff = a - b
                wins += int((diff < -TIE_TOL).sum()); losses += int((diff > TIE_TOL).sum())
                ps.append(wilcoxon_p(a, b)); fav.append("S" if (diff < -TIE_TOL).sum() > (diff > TIE_TOL).sum() else "C")
            ph = holm(ps)
            sig = [(f, p) for f, p in zip(fav, ph) if p < 0.05]
            out[f"auth-{dom}-vs{name}-sigS"] = str(sum(f == "S" for f, _ in sig))
            out[f"auth-{dom}-vs{name}-sigC"] = str(sum(f == "C" for f, _ in sig))
            out[f"auth-{dom}-vs{name}-wins"] = str(wins)
            out[f"auth-{dom}-vs{name}-losses"] = str(losses)
            out[f"auth-{dom}-n"] = str(T[ic].nunique())
        f10 = T[(T[ic] == 10)] if dom == "CEC2022" else None
        if f10 is not None:
            for alias, name in ((sarsa, "SARSA"), (rnd, "RANDOM"), (mphb, "MPHB")):
                out[f"auth-F10-{name}-esc"] = str(int((f10[f10.Alias == alias][vc] < 50).sum()))
    return out


def table_arms():
    """Table 1: arms, per-iteration FE and T, from configs/pathA.yaml (the values the tests check)."""
    pa = load_yaml("pathA.yaml")["arms"]
    what = {"PA-SARSA": "none (reference: MPHBS)",
            "PA-RND-FAIR": "uniform random assembly, no Q-table",
            "PA-RND-SYNC": "RND-FAIR + zero-FE MPA memory refresh",
            "PA-RND-AUTH": "authors' RANDOM mirror (+N re-evaluations)",
            "PA-SKEL": "no Phase~2 (no mediator)",
            "PA-MPHB": "authors' backbone without mediator"}
    rows = []
    for arm, desc in what.items():
        cells = []
        for dom, max_fe in (("CEC2022", 200000), ("FIR", 150000)):
            a = pa[dom].get(arm)
            if a is None:
                cells += ["--", "--"]
            else:
                T, fe = a["expected"]
                cells += [str((fe - 60) // T), str(T)]
        rows.append(f"{ARM[arm]} & {desc} & {cells[0]} & {cells[2]} & {cells[1]} & {cells[3]} \\\\")
    body = "\n".join(rows)
    tex = f"""% generated by scripts/paper_assets.py from configs/pathA.yaml -- do not edit
\\begin{{table*}}[t]
\\centering
\\caption{{Primary arms. All arms use the authors' final configuration of the domain (B-C1 on CEC2022, A-C1 on FIR)
and the same total budget (200{{,}}000 FE on CEC2022, 150{{,}}000 FE on FIR); the number of iterations $T$ follows from
the per-iteration cost. $N=30$; $E=24$ (CEC2022) and $72$ (FIR) mediator episodes per iteration.}}
\\label{{tab:arms}}
\\small
\\begin{{tabular}}{{llcccc}}
\\toprule
 & & \\multicolumn{{2}}{{c}}{{FE per iteration}} & \\multicolumn{{2}}{{c}}{{Iterations $T$}} \\\\
\\cmidrule(lr){{3-4}}\\cmidrule(lr){{5-6}}
Arm & Change relative to MPHBS & CEC2022 & FIR & CEC2022 & FIR \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
\\end{{table*}}
"""
    (GEN / "tab_arms.tex").write_text(tex, encoding="utf-8")


def main():
    GEN.mkdir(parents=True, exist_ok=True)
    s = json.loads((AN / "summary.json").read_text(encoding="utf-8"))
    load_yaml("pathA.yaml")         # fail early if the config is missing
    m = macros(s, s["H5_f10_escape"], s["V3_authors_mirror"], s["integrity"])
    m.update(instance_macros())
    m.update(authors_reanalysis())
    write_macros(m)
    table_arms()
    table_contrasts(s, "primary", GEN / "tab_primary.tex",
                    "Confirmatory contrasts (pre-registered H1--H4). Sig.\\ (A/C): number of instances "
                    "significant after Holm in favour of the anchor / comparator. $\\bar W$: mean paired win "
                    "probability of the anchor with 95\\% bootstrap CI. Verdicts by the frozen decision rule.",
                    "tab:primary")
    table_contrasts(s, "secondary", GEN / "tab_secondary.tex",
                    "Exploratory contrasts (H6--H8), same statistics as Table~\\ref{tab:primary}; "
                    "no claim rests on them.", "tab:secondary")
    table_h1()
    figure(s)
    print("assets written:", sorted(os.listdir(GEN)), sorted(os.listdir(FIG)))


if __name__ == "__main__":
    main()
