"""BBOB section of the Path A paper: macros, tables and figure from results/analysis/pathA_bbob.

Outputs: paper/generated/bbob.tex (\\res{bbob-...}), tab_bbob.tex, tab_bbob_groups.tex, paper/figures/fig_bbob.pdf
Usage:  python scripts/paper_bbob_assets.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from lakaie.experiment import load_yaml  # noqa: E402

AN = ROOT / "results" / "analysis" / "pathA_bbob"
GEN = ROOT / "paper" / "generated"
FIG = ROOT / "paper" / "figures"
NAME = {"B1": "learning: SARSA vs RND-FAIR", "B3": "mediator: SARSA vs SKEL"}
BLUE, ORANGE, GREY, INK, INK2 = "#2a78d6", "#eb6834", "#9a9893", "#0b0b0b", "#52514e"


def rel_tex(x):
    if x == 0:
        return "0"
    m, e = f"{abs(x):.1e}".split("e")
    return f"{'-' if x < 0 else ''}{m}{{\\times}}10^{{{int(e)}}}"


def main():
    s = json.loads((AN / "summary.json").read_text(encoding="utf-8"))
    if s.get("result") != "ok":
        raise SystemExit(f"BBOB analysis not ok: {s.get('result')}")
    m = {}
    rows = []
    for key, c in s["contrasts"].items():
        cid, bench = key.split("/")
        d = bench.split("-D")[1]
        k = f"bbob-{cid}-D{d}"
        m[f"{k}-wbar"] = f"{c['wbar']:.3f}"
        m[f"{k}-ci"] = f"[{c['ci_low']:.3f}, {c['ci_high']:.3f}]"
        m[f"{k}-siga"], m[f"{k}-sigc"] = str(c["n_sig_anchor"]), str(c["n_sig_comparator"])
        m[f"{k}-rel"] = rel_tex(c["rel_median"])
        m[f"{k}-verdict"] = c["verdict"]
        m[f"{k}-ties"] = str(c["n_solved_ties"])
        rows.append(f"{cid} & {NAME[cid].split(':')[0]} & $D={d}$ & {c['n_sig_anchor']}/{c['n_sig_comparator']} & "
                    f"{c['wbar']:.3f} & [{c['ci_low']:.3f}, {c['ci_high']:.3f}] & ${rel_tex(c['rel_median'])}$ & "
                    f"{c['verdict']} \\\\")
    integ = s["integrity"]
    m["bbob-runs"] = f"{sum(v['n_runs'] for v in integ.values()):,}"
    m["bbob-commit"] = s["git_commit"][:7]
    lines = ["% generated by scripts/paper_bbob_assets.py -- do not edit"]
    lines += [f"\\expandafter\\def\\csname res@{k}\\endcsname{{{v}}}" for k, v in sorted(m.items())]
    (GEN / "bbob.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")

    (GEN / "tab_bbob.tex").write_text(f"""% generated by scripts/paper_bbob_assets.py -- do not edit
\\begin{{table*}}[t]
\\centering
\\caption{{Exploratory BBOB extension (24 functions, 30 seed-paired runs each; errors below $10^{{-8}}$ set to
$10^{{-8}}$). Statistics and verdict rule as in Table~\\ref{{tab:primary}}; Sig.\\ (A/C) counts functions.}}
\\label{{tab:bbob}}
\\footnotesize
\\begin{{tabular}}{{lllcccccl}}
\\toprule
 & Question & Dim. & Sig.\\ (A/C) & $\\bar W$ & 95\\% CI & Rel.\\ diff. & Verdict \\\\
\\midrule
{chr(10).join(rows)}
\\bottomrule
\\end{{tabular}}
\\end{{table*}}
""", encoding="utf-8")

    groups = load_yaml("pathA_bbob.yaml")["groups"]
    grows = []
    for g, fids in groups.items():
        cells = []
        for cid in ("B1", "B3"):
            for d in (10, 20):
                v = s["groups"][f"{cid}/BBOB-D{d}/{g}"]
                cells.append(f"{v['mean_w']:.2f} ({v['sig_anchor']}/{v['sig_comparator']})")
        grows.append(f"{g} (f{fids[0]}--f{fids[-1]}) & " + " & ".join(cells) + " \\\\")
    (GEN / "tab_bbob_groups.tex").write_text(f"""% generated by scripts/paper_bbob_assets.py -- do not edit
\\begin{{table*}}[t]
\\centering
\\caption{{BBOB by function group: mean paired win probability of SARSA over the group's functions, and the number of
functions significant (Holm over all 24) in favour of SARSA / of the comparator.}}
\\label{{tab:bbob-groups}}
\\footnotesize
\\begin{{tabular}}{{lcccc}}
\\toprule
 & \\multicolumn{{2}}{{c}}{{B1: SARSA vs RND-FAIR}} & \\multicolumn{{2}}{{c}}{{B3: SARSA vs SKEL}} \\\\
\\cmidrule(lr){{2-3}}\\cmidrule(lr){{4-5}}
Group & $D=10$ & $D=20$ & $D=10$ & $D=20$ \\\\
\\midrule
{chr(10).join(grows)}
\\bottomrule
\\end{{tabular}}
\\end{{table*}}
""", encoding="utf-8")
    figure(s)
    print("bbob assets written")


def figure(s):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.lines import Line2D
    plt.rcParams.update({"font.family": "sans-serif", "font.size": 7, "axes.edgecolor": INK2,
                         "xtick.color": INK2, "ytick.color": INK2, "pdf.fonttype": 42,
                         "axes.spines.top": False, "axes.spines.right": False})
    fig, axes = plt.subplots(2, 2, figsize=(7.0, 6.4), sharey=True)
    for i, cid in enumerate(("B1", "B3")):
        for j, d in enumerate((10, 20)):
            ax = axes[i, j]
            T = pd.read_csv(AN / "tables" / f"{cid}_BBOB-D{d}.csv")
            c = s["contrasts"][f"{cid}/BBOB-D{d}"]
            y = list(range(len(T)))[::-1]
            ax.axvline(0.5, color=GREY, lw=0.8, ls=(0, (2, 2)))
            ax.axvspan(c["ci_low"], c["ci_high"], color=BLUE if c["wbar"] > 0.5 else ORANGE, alpha=0.12, lw=0)
            ax.axvline(c["wbar"], color=INK2, lw=1.0)
            for yy, r in zip(y, T.itertuples()):
                if r.significant_favours == "anchor":
                    ax.plot(r.w, yy, "o", ms=4.5, color=BLUE, mec="white", mew=0.6)
                elif r.significant_favours == "comparator":
                    ax.plot(r.w, yy, "v", ms=5, color=ORANGE, mec="white", mew=0.6)
                else:
                    ax.plot(r.w, yy, "o", ms=4, mfc="white", mec=GREY, mew=0.9)
            ax.set_yticks(y)
            ax.set_yticklabels([f"f{k}" for k in T.instance], fontsize=5.5)
            ax.set_xlim(-0.03, 1.03)
            ax.tick_params(axis="y", length=0)
            for b in (4.5, 9.5, 14.5, 18.5):          # group separators (f1-5 | 6-9 | 10-14 | 15-19 | 20-24)
                ax.axhline(len(T) - 1 - b, color="#e6e5e1", lw=0.6)
            ax.set_title(f"{NAME[cid]}, $D={d}$", fontsize=7, loc="left", color=INK)
    for ax in axes[-1]:
        ax.set_xlabel("paired win probability of SARSA ($\\hat w$)")
    fig.legend(handles=[Line2D([], [], marker="o", ls="", color=BLUE, mec="white", label="significant, favours SARSA"),
                        Line2D([], [], marker="v", ls="", color=ORANGE, mec="white", label="significant, favours comparator"),
                        Line2D([], [], marker="o", ls="", mfc="white", mec=GREY, label="not significant (Holm)"),
                        Line2D([], [], color=INK2, lw=1, label="$\\bar W$ (shaded: 95% CI)")],
               loc="lower center", ncol=4, frameon=False, fontsize=6.5, bbox_to_anchor=(0.5, -0.005))
    fig.tight_layout(rect=(0, 0.035, 1, 1), h_pad=1.0)
    fig.savefig(FIG / "fig_bbob.pdf")
    fig.savefig(FIG / "fig_bbob.png", dpi=180)


if __name__ == "__main__":
    main()
