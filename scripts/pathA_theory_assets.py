"""Numbers and the table of the theory section of the Path A paper, from scripts/pathA_learning_signal.py.

Output: paper/generated/theory.tex (\\res keys th-<bench>-<stat> and Table tab:theory)
Usage:  python scripts/pathA_theory_assets.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
AN = ROOT / "results" / "analysis" / "pathA_theory"
OUT = ROOT / "paper" / "generated" / "theory.tex"
ALPHA, GAMMA = 0.10, 0.30


def q(x, p):
    return float(np.quantile(x, p))


def main():
    T = pd.read_csv(AN / "learning_signal.csv")
    R = {}
    beta = ALPHA * (1 - GAMMA)
    R["th-beta"] = f"{beta:.2f}"
    R["th-memory"] = f"{1 / beta:.1f}"
    R["th-sdfactor"] = f"{ALPHA / np.sqrt(beta * (2 - beta)):.3f}"
    R["th-runs"] = int(len(T))
    rows = []
    for b, g in T.groupby("bench"):
        k = "CEC" if b == "CEC2022" else "FIR"
        for col, fmt in (("p_plus", "{:.1%}"), ("p_minus", "{:.1%}"), ("reward_sd", "{:.2f}"), ("Q_sd_pred", "{:.3f}"),
                         ("tau_action", "{:.3f}"), ("z_typical", "{:.2f}"), ("split_half_rho", "{:.2f}"),
                         ("Qmid_validity_rho", "{:.2f}"), ("median_updates_per_updated_cell", "{:.0f}")):
            R[f"th-{k}-{col}"] = fmt.format(float(g[col].median())).replace("%", r"\%")
        R[f"th-{k}-valid-pos"] = int((g.Qmid_validity_rho > 0).sum())
        R[f"th-{k}-n"] = int(len(g))
        R[f"th-{k}-rel-q"] = f"[{q(g.split_half_rho, .25):.2f}, {q(g.split_half_rho, .75):.2f}]"
        R[f"th-{k}-valid-q"] = f"[{q(g.Qmid_validity_rho, .25):.2f}, {q(g.Qmid_validity_rho, .75):.2f}]"
        name = "CEC2022 ($D=20$)" if k == "CEC" else "FIR ($D=31$)"
        rows.append(f"{name} & {len(g)} & {R[f'th-{k}-p_plus']} & {R[f'th-{k}-reward_sd']} & {R[f'th-{k}-Q_sd_pred']} & "
                    f"{R[f'th-{k}-tau_action']} & {R[f'th-{k}-z_typical']} & {R[f'th-{k}-split_half_rho']} "
                    f"{R[f'th-{k}-rel-q']} & {R[f'th-{k}-Qmid_validity_rho']} {R[f'th-{k}-valid-q']} \\\\")
    tab = r"""\begin{table*}[!t]
\centering
\caption{Post hoc check of Section~\ref{sec:theory} (5 runs per instance; medians over runs, interquartile ranges in
brackets). $p_+$: share of episodes with reward $+1$. $\sigma$: reward standard deviation. $\mathrm{sd}(Q)$: noise
standard deviation of a table entry predicted by Proposition~\ref{prop:noise}. $\hat\tau$: between-cell standard deviation
of the mean reward of the choices tried (method of moments, cells with at least 30 trials). $z$: separation of two
cells that differ by $\hat\tau$, Corollary~\ref{cor:order}. $\rho_{1/2}$: Spearman correlation of the cells' mean
rewards between the first and second half of the run. $\rho_Q$: Spearman correlation between the table at mid-run and
the cells' mean rewards in the second half.}
\label{tab:theory}
\footnotesize
\begin{tabular}{lcccccccc}
\toprule
Benchmark & runs & $p_+$ & $\sigma$ & $\mathrm{sd}(Q)$ & $\hat\tau$ & $z$ & $\rho_{1/2}$ & $\rho_Q$ \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}
\end{table*}
"""
    body = "% generated by scripts/pathA_theory_assets.py -- do not edit\n" + "".join(
        f"\\expandafter\\def\\csname res@{k}\\endcsname{{{v}}}\n" for k, v in sorted(R.items()))
    OUT.write_text(body, encoding="utf-8")
    (OUT.parent / "tab_theory.tex").write_text("% generated by scripts/pathA_theory_assets.py -- do not edit\n" + tab,
                                               encoding="utf-8")
    print(json.dumps(R, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
