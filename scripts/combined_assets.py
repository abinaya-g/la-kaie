    rows = []
    for tag, pair, lab in (("PD", "PSO+DE", "PSO + DE"), ("GW", "GWO+WOA", "GWO + WOA")):
        rows.append(
            rf"{lab} & \res{{X-{tag}-medA}} & \res{{X-{tag}-ngt}}/\res{{X-{tag}-neq}}/\res{{X-{tag}-nlt}} & "
            rf"\res{{X-{tag}-p}} & \res{{X-{tag}-pholm}} & \res{{X-{tag}-ppratt}} / \res{{X-{tag}-pzsplit}} & "
            rf"\res{{X-{tag}-sige}}/\res{{X-{tag}-siga}} \\")
