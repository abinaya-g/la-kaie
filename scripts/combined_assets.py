"""Assets of the combined manuscript (paper_combined/).

Every number in the manuscript comes from a result file through a macro  \\res{<study>-<key>}:
  E-  study II  (eigen-frame exchange)   from paper_eswa/generated/results.tex
  A-  study I   (learning, theory, BBOB) from paper/generated/{results,theory,bbob}.tex
  X-  study III (transfer)               from results/analysis/eswa_xhyb/ (H3_summary.json, H3_per_instance.csv)
Tables and figures of studies I and II are copied from the generated folders of the two source manuscripts;
hypothesis labels are renamed so that the three studies do not share names:
  study I  H1..H8 -> L1..L8     study II  H1, H2 -> F1, F2     study III  H3 -> T1
Usage:  python scripts/combined_assets.py
"""
from __future__ import annotations

import json
import re
import shutil
from pathlib import Path

import matplotlib
import numpy as np
import pandas as pd

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "paper_combined"
GEN = OUT / "generated"
FIG = OUT / "figures"
A_DIR, E_DIR = ROOT / "paper", ROOT / "paper_eswa"
XH = ROOT / "results" / "analysis" / "eswa_xhyb"

KEY = re.compile(r"\\expandafter\\def\\csname res@([^\\]+)\\endcsname\{(.*)\}\s*$")


def read_keys(path: Path, prefix: str) -> dict[str, str]:
    out = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        m = KEY.match(line)
        if m:
            out[prefix + m.group(1)] = m.group(2)
    return out


def sci(p: float) -> str:
    if p >= 0.001:
        return f"{p:.3f}"
    mant, exp = f"{p:.1e}".split("e")
    return rf"\ensuremath{{{mant}{{\times}}10^{{{int(exp)}}}}}"


def f3(x: float) -> str:
    return f"{x:.3f}"


def med(x: float) -> str:
    if x <= 1.0001e-8:
        return r"\ensuremath{<}$10^{-8}$"
    if x >= 100:
        return f"{x:.0f}"
    if x >= 0.01:
        return f"{x:.2f}"
    mant, exp = f"{x:.1e}".split("e")
    return rf"\ensuremath{{{mant}{{\times}}10^{{{int(exp)}}}}}"


def transfer_keys() -> dict[str, str]:
    s = json.loads((XH / "H3_summary.json").read_text())
    k = {}
    short = {"PSO+DE": "PD", "GWO+WOA": "GW"}
    for pair, r in s["H3"].items():
        p = short[pair]
        k[f"X-{p}-n"] = str(r["n"])
        k[f"X-{p}-medA"] = f3(r["median_A"])
        k[f"X-{p}-meanA"] = f3(r["mean_A"])
        k[f"X-{p}-ngt"] = str(r["n_A_gt_half"])
        k[f"X-{p}-nlt"] = str(r["n_A_lt_half"])
        k[f"X-{p}-neq"] = str(r["n_A_eq_half"])
        k[f"X-{p}-p"] = sci(r["p_one_sided"])
        k[f"X-{p}-pholm"] = sci(r["p_holm"])
        k[f"X-{p}-ppratt"] = sci(r["p_pratt"])
        k[f"X-{p}-pzsplit"] = sci(r["p_zsplit"])
        k[f"X-{p}-sige"] = str(r["inst_sig_eigen"])
        k[f"X-{p}-siga"] = str(r["inst_sig_axis"])
        for b, v in r["by_bench"].items():
            bb = "B20" if b.startswith("BBOB") else "FIR"
            k[f"X-{p}-{bb}-medA"] = f3(v["median_A"])
            k[f"X-{p}-{bb}-n"] = str(v["n"])
            k[f"X-{p}-{bb}-sige"] = str(v["sig_eigen"])
            k[f"X-{p}-{bb}-siga"] = str(v["sig_axis"])
    arm = {"PD-R": "PDR", "PD-EIG": "PDE", "GW-R": "GWR", "GW-EIG": "GWE"}
    for name, tag in (("ellipsoid f10/f2", "ell"), ("rastrigin f15/f3", "ras")):
        for a, v in s["rotation_pairs"][name].items():
            k[f"X-{tag}-rot-{arm[a]}"] = med(v["median_rotated"])
            k[f"X-{tag}-sep-{arm[a]}"] = med(v["median_separable"])
    for key, v in s["acceptance_first_quarter_median"].items():
        a, f = key.split("/")
        k[f"X-acc-{arm[a]}-{f}"] = f"{100 * v:.1f}"
    k["X-runs"] = "3\\,840"
    return k


def write_results():
    keys = {}
    keys.update(read_keys(E_DIR / "generated" / "results.tex", "E-"))
    for f in ("results.tex", "theory.tex", "bbob.tex"):
        keys.update(read_keys(A_DIR / "generated" / f, "A-"))
    keys.update(transfer_keys())
    lines = ["% generated by scripts/combined_assets.py -- do not edit"]
    lines += [rf"\expandafter\def\csname res@{k}\endcsname{{{v}}}" for k, v in sorted(keys.items())]
    (GEN / "results.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(len(keys), "result keys")


def copy_tables():
    study1 = ["tab_arms", "tab_primary", "tab_h1", "tab_theory", "tab_secondary", "tab_bbob_groups"]
    study2 = ["tab_confirm", "tab_rotation", "tab_ranks", "tab_wtl", "tab_cost", "tab_ablation", "tab_ea4eig"]
    for t in study1:
        s = (A_DIR / "generated" / f"{t}.tex").read_text(encoding="utf-8")
        s = re.sub(r"\bH(\d[ab]?)\b", r"L\1", s)
        s = s.replace("H1--H4", "L1--L4").replace("H6--H8", "L6--L8")
        (GEN / f"{t}.tex").write_text(s, encoding="utf-8")
    for t in study2:
        s = (E_DIR / "generated" / f"{t}.tex").read_text(encoding="utf-8")
        s = re.sub(r"\bH([12])\b", r"F\1", s)
        s = s.replace("H1$'$", "F1$'$").replace("H2$'$", "F2$'$")
        s = s.replace(r"\{H1, H2\}", r"\{F1, F2\}")
        (GEN / f"{t}.tex").write_text(s, encoding="utf-8")


def copy_figures():
    for name in ("fig_heldout.pdf", "fig_mechanism.pdf", "fig_ranks.pdf", "fig_wtl_map.pdf", "fig_architecture_tikz.tex"):
        shutil.copy(E_DIR / "figures" / name, FIG / name)
    for name in ("fig_forest.pdf", "fig_instances.pdf", "fig1_loop.tex", "fig_dose.pdf"):
        shutil.copy(A_DIR / "figures" / name, FIG / name)
    # the combined text does not number the native-move equations of the parent algorithms
    p = FIG / "fig_architecture_tikz.tex"
    s = p.read_text(encoding="utf-8")
    s = s.replace(r"\\Eq.~\eqref{eq:hba}", "").replace(r"\\Eqs.~\eqref{eq:mpa}, \eqref{eq:memory}", r"\\Eq.~\eqref{eq:memory}")
    p.write_text(s, encoding="utf-8")


